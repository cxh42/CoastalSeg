import argparse
import csv
import os
import sys
from datetime import datetime
from typing import Dict, List, Tuple

import matplotlib.pyplot as plt
import matplotlib.dates as mdates

CLASSES = ['Background', 'Cobbles', 'Dry sand', 'Plant', 'Sky', 'Water', 'Wet sand']
COLORS = [
    'black',         # Background
    'dimgray',       # Cobbles
    'khaki',         # Dry sand
    'green',         # Plant
    'skyblue',       # Sky
    'blue',          # Water
    'tan'            # Wet sand
]


def parse_csv(csv_path: str) -> Tuple[List[datetime], Dict[str, List[float]]]:
    dates: List[datetime] = []
    data_points: List[Tuple[datetime, Dict[str, float]]] = []
    
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            date_str = row.get("image_date", "").strip()
            if not date_str:
                continue
            
            try:
                dt = datetime.strptime(date_str, "%Y-%m-%d %H:%M:%S")
            except ValueError:
                try:
                    dt = datetime.strptime(date_str, "%Y-%m-%d %H:%M")
                except ValueError:
                    print(f"Skipping invalid date: {date_str}")
                    continue
            
            vals = {}
            for cls in CLASSES:
                try:
                    vals[cls] = float(row.get(cls, 0.0))
                except ValueError:
                    vals[cls] = 0.0
            data_points.append((dt, vals))

    return data_points


def plot_trends(dates: List[datetime], data: Dict[str, List[float]], output_path: str, title: str, mode: str):
    fig, ax = plt.subplots(figsize=(12, 6))
    
    # Sort data for plotting lines
    # Data is already sorted in main based on mode
    
    for idx, cls in enumerate(CLASSES):
        if any(v > 0 for v in data[cls]):
            # If mode is time, using scatter might be better if data is noisy across days?
            # User asked for 'line chart' "按照一天中的时间和各类别占比画一个折线图".
            # So line chart it is.
            ax.plot(dates, data[cls], label=cls, color=COLORS[idx], marker='o', markersize=3, linestyle='-', linewidth=1.5, alpha=0.8)

    ax.set_ylabel("Coverage Percentage (%)")
    ax.set_title(title)
    ax.legend(bbox_to_anchor=(1.05, 1), loc='upper left')
    
    if mode == 'time':
        # Format X axis as Hour:Minute, assume all on same dummy day
        ax.xaxis.set_major_formatter(mdates.DateFormatter('%H:%M'))
        ax.set_xlabel("Time of Day")
    else:
        ax.xaxis.set_major_formatter(mdates.DateFormatter('%Y-%m-%d'))
        ax.set_xlabel("Date")
        fig.autofmt_xdate()
        
    ax.xaxis.set_major_locator(mdates.AutoDateLocator())
    
    plt.grid(True, linestyle='--', alpha=0.5)
    plt.tight_layout()
    plt.savefig(output_path, dpi=150)
    print(f"Plot saved to: {output_path}")


def main():
    parser = argparse.ArgumentParser(description="Visualize segmentation trends from summary.csv")
    parser.add_argument("csv_file", help="Path to summary.csv generated by batch_infer.py")
    parser.add_argument("--output", default="trends_plot.png", help="Output path for the plot image")
    parser.add_argument("--title", default="Segmentation Class Composition", help="Plot title")
    parser.add_argument("--mode", choices=['date', 'time'], default='date', help="Plot mode: 'date' (default) or 'time' (diurnal)")
    
    args = parser.parse_args()
    
    if not os.path.exists(args.csv_file):
        print(f"Error: File not found: {args.csv_file}")
        sys.exit(1)
        
    print(f"Parsing {args.csv_file}...")
    raw_data = parse_csv(args.csv_file)
    
    if not raw_data:
        print("No valid data found.")
        sys.exit(1)
        
    # Sort and Prepare data based on mode
    if args.mode == 'time':
        # Normalize all dates to same dummy date (e.g. 2000-01-01) keeping time
        # Sort by time
        dummy_date = datetime(2000, 1, 1)
        # Transform tuples: (dummy_dt, vals)
        transformed = []
        for dt, vals in raw_data:
            new_dt = dt.replace(year=dummy_date.year, month=dummy_date.month, day=dummy_date.day)
            transformed.append((new_dt, vals))
        
        # Sort by time
        transformed.sort(key=lambda x: x[0])
        
        plot_dates = [x[0] for x in transformed]
        plot_data = {cls: [x[1][cls] for x in transformed] for cls in CLASSES}
        
    else: # date
        # Sort by full date
        raw_data.sort(key=lambda x: x[0])
        
        plot_dates = [x[0] for x in raw_data]
        plot_data = {cls: [x[1][cls] for x in raw_data] for cls in CLASSES}

    print(f"Plotting {len(plot_dates)} data points...")
    plot_trends(plot_dates, plot_data, args.output, args.title, args.mode)


if __name__ == "__main__":
    main()
